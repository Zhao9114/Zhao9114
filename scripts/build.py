def main() -> None:
    which = sys.argv[1:] or list(THEMES)
    out = ROOT / "out"
    for t in which:
        THEMES[t].build()
        text = readme_voyage(f"assets/{t}", RAW) if t == "voyage" else readme(t, f"assets/{t}", f"{RAW}/contrib-{CONTRIB[t]}.svg")
        (ROOT / "README.md").write_text(text, encoding="utf-8")
        print("built", t)


if __name__ == "__main__":
    main()
