"""Build every theme's SVG assets, its README, and a local GitHub-like preview page."""
import sys
from pathlib import Path

import theme_voyage
from common import NAV, PROJECTS, ROOT

THEMES = {"voyage": theme_voyage}
CONTRIB = {"beach": "beach", "wanted": "map", "voyage": "sea", "manga": "manga"}
SKILL_THEME = {"beach": "light", "wanted": "light", "voyage": "dark", "manga": "light"}
RAW = "https://raw.githubusercontent.com/Zhao9114/Zhao9114/output"
# bump after changing the art so browsers and GitHub's image cache fetch the new SVGs
ASSET_VERSION = "3"
SKILLS = [
    "python,java,kotlin,dart,ts,js,c,cpp",  # languages
    "html,css,react,nextjs,vue,vite,tailwind,materialui,flutter",  # frontend
    "nodejs,nestjs,flask,graphql,postgres,mysql,mongodb,sqlite,supabase",  # backend + data
    "firebase,aws,vercel,docker,kubernetes,githubactions,git,linux,wordpress",  # cloud + devops
    "pytorch,tensorflow,wasm,figma,androidstudio,vitest",  # ML + tools
]
# portfolio skills that skillicons.dev has no icon for
SKILLS_EXTRA = "React Native · Pandas · NumPy · Stripe · DigitalOcean · Odoo · Sitecore · Claude, OpenAI and Gemini APIs"


def readme(theme: str, asset: str, contrib_src: str) -> str:
    """asset: prefix for theme SVGs, contrib_src: URL of the generated widget."""
    a = lambda n: f"{asset}/{n}.svg"  # noqa: E731
    nav = "\n".join(
        f'  <a href="{url}"><img src="{a("nav-" + label.lower())}" width="15%" alt="{label}" /></a>' for label, url in NAV
    )
    cards = []
    for i in range(0, len(PROJECTS), 2):
        pair = "\n".join(
            f'  <a href="{p["url"]}"><img src="{a("card-" + p["slug"])}" width="49%" alt="{p["name"]}" /></a>'
            for p in PROJECTS[i : i + 2]
        )
        cards.append(f'<p align="center">\n{pair}\n</p>')
    skills = "\n".join(
        f'  <img src="https://skillicons.dev/icons?i={row}&theme={SKILL_THEME[theme]}&perline=7" alt="skills" /><br/>'
        for row in SKILLS
    )
    extra = ""
    if theme in ("voyage", "beach"):
        extra = (
            '\n<!-- your existing GIF, kept as a "view from the deck" strip -->\n'
            '<img src="https://raw.githubusercontent.com/Zhao9114/Zhao9114/main/assets/thousand-sunny_800.gif" width="100%" alt="at sea" />\n'
        )
    snake = ""
    return f"""<!-- {theme.upper()} theme: generated by scripts/build.py, widgets refreshed by .github/workflows/widgets.yml -->

<a href="{NAV[0][1]}"><img src="{a("hero")}" width="100%" alt="Zheng Yao Wong, full-stack developer" /></a>

<p align="center">
{nav}
</p>
{extra}
<img src="{a("about")}" width="100%" alt="About" />

<img src="{a("h-projects")}" width="100%" alt="Projects" />

{chr(10).join(cards)}

<img src="{a("h-stack")}" width="100%" alt="Tech stack" />

<p align="center">
{skills}
</p>

<img src="{a("h-log")}" width="100%" alt="Contributions" />

<img src="{contrib_src}" width="100%" alt="Contribution chart" />
{snake}
<img src="{a("footer")}" width="100%" alt="Footer" />
"""


def readme_voyage(asset: str, raw: str) -> str:
    """Night Voyage gets extra animated pieces, so it has its own layout."""
    a = lambda n: f"{asset}/{n}.svg?v={ASSET_VERSION}"  # noqa: E731
    nav = "\n".join(
        f'  <a href="{url}"><img src="{a("nav-" + label.lower())}" width="15%" alt="{label}" /></a>' for label, url in NAV
    )
    cards = []
    for i in range(0, len(PROJECTS), 2):
        pair = "\n".join(
            f'  <a href="{p["url"]}"><img src="{a("card-" + p["slug"])}" width="49%" alt="{p["name"]}" /></a>'
            for p in PROJECTS[i : i + 2]
        )
        cards.append(f'<p align="center">\n{pair}\n</p>')
    skills = "\n".join(
        f'  <img src="https://skillicons.dev/icons?i={row}&theme=dark&perline=9" alt="skills" /><br/>' for row in SKILLS
    ) + f"\n  <sub>also: {SKILLS_EXTRA}</sub>"
    return f"""<!-- NIGHT VOYAGE theme, Grand Line edition: built by scripts/build.py, chart refreshed daily by .github/workflows/widgets.yml -->

<a href="{NAV[0][1]}"><img src="{a("hero")}" width="100%" alt="Zheng Yao Wong, full-stack developer" /></a>

<p align="center">
{nav}
</p>

<img src="https://raw.githubusercontent.com/Zhao9114/Zhao9114/main/assets/thousand-sunny_800.gif" width="100%" alt="Thousand Sunny at sea" />

<img src="{a("about")}" width="100%" alt="About" />

<img src="{a("chest")}" width="100%" alt="Current arc, now building: Combat Capture" />

<img src="{a("h-projects")}" width="100%" alt="Bounties: projects" />

{chr(10).join(cards)}

<img src="{a("sea-king")}" width="100%" alt="A Sea King rising out of the water" />

<img src="{a("h-stack")}" width="100%" alt="Devil Fruits: tech stack" />

<p align="center">
{skills}
</p>

<img src="{a("h-log")}" width="100%" alt="Log Pose: contributions" />

<img src="{raw}/contrib-sea.svg" width="100%" alt="Grand Line contribution chart" />

<a href="mailto:zhengyaowong.cs@gmail.com"><img src="{a("den-den-mushi")}" width="100%" alt="Den Den Mushi: email zhengyaowong.cs@gmail.com" /></a>

<p align="center">
  <img src="assets/gifs/walking.gif" width="45%" alt="Walking on to the next adventure" />
</p>

<img src="{a("footer")}" width="100%" alt="Footer" />
"""


def main() -> None:
    which = sys.argv[1:] or list(THEMES)
    out = ROOT / "out"
    for t in which:
        THEMES[t].build()
        text = readme_voyage(f"assets/{t}", RAW) if t == "voyage" else readme(t, f"assets/{t}", f"{RAW}/contrib-{CONTRIB[t]}.svg")
        (ROOT / "README.md").write_text(text, encoding="utf-8")
        print("built", t)


if __name__ == "__main__":
    main()
