"""Build every theme's SVG assets, its README, and a local GitHub-like preview page."""
import sys
from pathlib import Path

import theme_voyage
from common import NAV, PROJECTS, ROOT

THEMES = {"voyage": theme_voyage}
CONTRIB = {"beach": "beach", "wanted": "map", "voyage": "sea", "manga": "manga"}
SKILL_THEME = {"beach": "light", "wanted": "light", "voyage": "dark", "manga": "light"}
RAW = "https://raw.githubusercontent.com/Zhao9114/Zhao9114/output"
SKILLS = [
    "python,java,ts,js,c,cpp,html",
    "react,vue,flutter,tailwind,graphql,nodejs",
    "postgres,mysql,mongodb,firebase,aws,docker,kubernetes",
    "git,linux,androidstudio,pytorch,tensorflow",
]


def readme(theme: str, asset: str, contrib_src: str) -> str:
    """asset: prefix for theme SVGs, contrib_src: URL of the generated widget."""
    a = lambda n: f"{asset}/{n}.svg"  # noqa: E731
    nav = "\n".join(
        f'  <a href="{url}"><img src="{a("nav-" + label.lower())}" width="15%" alt="{label}" /></a>' for label, url in NAV
    )
    cards = []
    for i in range(0, len(PROJECTS), 2):
        pair = "\n".join(
            f'  <a href="{p["url"]}"><img src="{a("card-" + p["slug"])}" width="49%" alt="{p["name"]}" /></a>'
            for p in PROJECTS[i : i + 2]
        )
        cards.append(f'<p align="center">\n{pair}\n</p>')
    skills = "\n".join(
        f'  <img src="https://skillicons.dev/icons?i={row}&theme={SKILL_THEME[theme]}&perline=7" alt="skills" /><br/>'
        for row in SKILLS
    )
    extra = ""
    if theme in ("voyage", "beach"):
        extra = (
            '\n<!-- your existing GIF, kept as a "view from the deck" strip -->\n'
            '<img src="https://raw.githubusercontent.com/Zhao9114/Zhao9114/main/assets/thousand-sunny_800.gif" width="100%" alt="at sea" />\n'
        )
    snake = ""
    return f"""<!-- {theme.upper()} theme: generated by scripts/build.py, widgets refreshed by .github/workflows/widgets.yml -->

<a href="{NAV[0][1]}"><img src="{a("hero")}" width="100%" alt="Zheng Yao Wong, full-stack developer" /></a>

<p align="center">
{nav}
</p>
{extra}
<img src="{a("about")}" width="100%" alt="About" />

<img src="{a("h-projects")}" width="100%" alt="Projects" />

{chr(10).join(cards)}

<img src="{a("h-stack")}" width="100%" alt="Tech stack" />

<p align="center">
{skills}
</p>

<img src="{a("h-log")}" width="100%" alt="Contributions" />

<img src="{contrib_src}" width="100%" alt="Contribution chart" />
{snake}
<img src="{a("footer")}" width="100%" alt="Footer" />
"""


